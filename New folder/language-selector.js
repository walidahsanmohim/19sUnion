    let currentLanguage = localStorage.getItem('alawda_language') || 'en';

    function setLanguage(lang) {
      currentLanguage = lang;
      localStorage.setItem('alawda_language', lang);
      updatePageLanguage();
    }

    function updatePageLanguage() {
      const t = translations[currentLanguage];

      // Update header elements
      const companyName = document.getElementById('company-name');
      if (companyName) companyName.textContent = t.company_name;

      const tagline = document.getElementById('tagline');
      if (tagline) tagline.textContent = t.tagline;

      const heroTitle = document.getElementById('hero-title');
      if (heroTitle) heroTitle.textContent = t.hero_title;

      const heroSubtitle = document.getElementById('hero-subtitle');
      if (heroSubtitle) heroSubtitle.textContent = t.hero_subtitle;

      const ctaButton = document.getElementById('cta-button');
      if (ctaButton) ctaButton.textContent = t.cta_button;

      // Update navigation
      const navLinks = document.querySelectorAll('nav a');
      if (navLinks.length >= 3) {
        navLinks[0].textContent = currentLanguage === 'en' ? 'Products' : 'পণ্য';
        navLinks[1].textContent = currentLanguage === 'en' ? 'About' : 'সম্পর্কে';
        navLinks[2].textContent = currentLanguage === 'en' ? 'Contact' : 'যোগাযোগ';
      }

      // Update auth button
      const authBtn = document.getElementById('auth-btn');
      if (authBtn) authBtn.textContent = t.login;

      // Update sections
      const productsHeading = document.querySelector('#products h3');
      if (productsHeading) productsHeading.textContent = t.products_title;

      const aboutHeading = document.querySelector('#about h3');
      if (aboutHeading) aboutHeading.textContent = t.about_title;

      const aboutText = document.querySelector('#about p');
      if (aboutText) aboutText.textContent = t.about_text;

      const contactHeading = document.querySelector('#contact h3');
      if (contactHeading) contactHeading.textContent = t.contact_title;

      // Update search placeholder
      const searchInput = document.getElementById('product-search');
      if (searchInput) searchInput.placeholder = t.search_placeholder;

      // Update category filter
      const categorySelect = document.getElementById('category-filter');
      if (categorySelect && categorySelect.options[0]) {
        categorySelect.options[0].textContent = t.all_categories;
      }

      // Update testimonials
      const testimonialsHeading = document.querySelector('#testimonials h3');
      if (testimonialsHeading) testimonialsHeading.textContent = t.testimonials_title;

      // Update newsletter
      const newsletterHeading = document.querySelector('#newsletter h3');
      if (newsletterHeading) newsletterHeading.textContent = t.newsletter_title;

      const newsletterText = document.querySelector('#newsletter p');
      if (newsletterText) newsletterText.textContent = t.newsletter_subtitle;

      const newsletterButton = document.querySelector('#newsletter button');
      if (newsletterButton) newsletterButton.textContent = t.subscribe;

      // Update footer
      const footerAbout = document.querySelector('footer p');
      if (footerAbout) footerAbout.textContent = t.footer_about;

      const footerHeadings = document.querySelectorAll('footer h4');
      if (footerHeadings.length >= 2) {
        footerHeadings[0].textContent = t.footer_company;
        footerHeadings[1].textContent = t.footer_customer;
      }

      const footerLinks = document.querySelectorAll('footer li a');
      if (footerLinks.length >= 6) {
        footerLinks[0].textContent = t.footer_about_us;
        footerLinks[1].textContent = t.footer_privacy;
        footerLinks[2].textContent = t.footer_terms;
        footerLinks[3].textContent = t.footer_my_account;
        footerLinks[4].textContent = t.footer_track_order;
        footerLinks[5].textContent = t.footer_support;
      }

      const copyrightText = document.querySelector('footer .border-t p');
      if (copyrightText) copyrightText.textContent = t.copyright;

      // Update chatbot
      const chatbotTitle = document.querySelector('#chatbot-window h3');
      if (chatbotTitle) chatbotTitle.textContent = t.chatbot_title;

      const chatInput = document.getElementById('chat-input');
      if (chatInput) chatInput.placeholder = t.type_message;

      const sendButton = document.getElementById('send-message');
      if (sendButton && sendButton.nextElementSibling) {
        sendButton.nextElementSibling.textContent = t.send;
      }

      // Update quick replies
      const quickReplies = document.querySelectorAll('.quick-reply');
      t.quick_replies.forEach((reply, index) => {
        if (quickReplies[index]) quickReplies[index].textContent = reply;
      });

      // Update language selector
      const langSelector = document.getElementById('language-selector');
      if (langSelector) langSelector.value = currentLanguage;
    }

    // Initialize language on page load
    document.addEventListener('DOMContentLoaded', () => {
      updatePageLanguage();

      // Add language selector event listener
      const langSelector = document.getElementById('language-selector');
      if (langSelector) {
        langSelector.addEventListener('change', (e) => {
          setLanguage(e.target.value);
        });
      }
    });
